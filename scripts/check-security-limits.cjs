const assert=require('node:assert/strict');
const {createHash,randomUUID}=require('node:crypto');
const {readFileSync}=require('node:fs');
const {Pool}=require('pg');
require('../test/register.cjs');
async function main(){
 const url=new URL(process.env.DATABASE_URL||'');
 if(!['127.0.0.1','localhost'].includes(url.hostname)||url.pathname!='/security_test')throw new Error('Only a disposable local security_test database is permitted');
 const pool=new Pool({connectionString:url.toString()});
 await pool.query(readFileSync('scripts/security-rate-limits.sql','utf8'));
 const {rateLimit,rateAdmission}=require('../.test-build/src/lib/rate-limit.js');
 await pool.query('TRUNCATE tollbooth_security_rate_limits');
 const retained=randomUUID();const hash=createHash('sha256').update(retained).digest('hex');
 await pool.query("INSERT INTO tollbooth_security_rate_limits(key,count,reset_at) VALUES($1,1,now()+interval '1 hour')",[hash]);
 await pool.query("INSERT INTO tollbooth_security_rate_limits(key,count,reset_at) SELECT 'expired-'||n,1,now()-interval '2 hours' FROM generate_series(1,25) n");
 assert.equal((await rateLimit(retained,{limit:3,windowMs:60000})).remaining,1);
 assert.equal(Number((await pool.query('SELECT count(*) FROM tollbooth_security_rate_limits')).rows[0].count),6,'cleanup is bounded to twenty expired keys');
 await pool.query("UPDATE tollbooth_security_rate_limits SET count=2147483647 WHERE key=$1",[hash]);
 assert.equal((await rateLimit(retained,{limit:3,windowMs:60000})).ok,false);
 assert.equal((await pool.query("SELECT count FROM tollbooth_security_rate_limits WHERE key=$1",[hash])).rows[0].count,4,'counter saturates before addition');
 const key=randomUUID();
 const results=await Promise.all(Array.from({length:50},()=>rateLimit(key,{limit:3,windowMs:60000})));
 assert.equal(results.filter(r=>r.ok).length,3);
 const compositeGlobal=randomUUID(),compositeCaller=randomUUID();
 const budgets=[{key:compositeGlobal,limit:3,windowMs:60000},{key:compositeCaller,limit:1,windowMs:60000}];
 assert.equal(await rateAdmission(budgets),true);
 for(let n=0;n<10;n++)assert.equal(await rateAdmission(budgets),false);
 const globalHash=createHash('sha256').update(compositeGlobal).digest('hex');
 assert.equal((await pool.query('SELECT count FROM tollbooth_security_rate_limits WHERE key=$1',[globalHash])).rows[0].count,1,'denied caller does not spend global budget');
 await pool.query('UPDATE tollbooth_security_rate_limits SET count=3 WHERE key=$1',[globalHash]);
 const before=Number((await pool.query('SELECT count(*) FROM tollbooth_security_rate_limits')).rows[0].count);
 for(let n=0;n<10;n++)assert.equal(await rateAdmission([{key:compositeGlobal,limit:3,windowMs:60000},{key:'new-'+randomUUID(),limit:1,windowMs:60000}]),false);
 assert.equal(Number((await pool.query('SELECT count(*) FROM tollbooth_security_rate_limits')).rows[0].count),before,'global denial creates no caller keys');
 const race=randomUUID();const composite=await Promise.all(Array.from({length:20},(_,n)=>rateAdmission([{key:race,limit:3,windowMs:60000},{key:race+':'+n,limit:1,windowMs:60000}])));
 assert.equal(composite.filter(Boolean).length,3,'composite concurrent cap');
 await pool.end();
 await global.axxesPgPool?.end();
 console.log('Postgres concurrency: exactly 3 of 50 admitted');
}
main().catch(error=>{console.error(error.name,error.message);process.exitCode=1;});
